/**
 * Code 128（Code Set B）條碼編碼。
 * 表7布疋條碼標籤需要能實際被掃描槍讀取，故不使用示意圖形，直接產生符合規格的條碼模組。
 * Code Set B 涵蓋 ASCII 32–126，足以編碼「胚布編號＋流水號」格式（如 T3268305-01）。
 */

/** Code 128 標準符號表：107 組（0–102 資料值、103–105 起始碼、106 停止碼），每組為 bar/space 交替的模組寬度 */
