/** 皇加產品表的一列（原表欄位，未經加工） */
export interface ProductCatalogRow {
  categoryCode: string
  /** 原表 ITEM，即皇加品名 */
  item: string
  /** 原表 COMPOSITION，即成分 */
  composition: string
  /** 碼重 (G/Y)；原表空白者為 undefined */
  weightGY?: number
  /** 幅寬原文（如 58/60"、120"）；原表空白者為 undefined */
  widthSpec?: string
  /** 幅寬數值（取範圍低標，供接疋與規格運算用） */
  width?: number
  /** 厚度 (mm)：原表值照抄 */
  thicknessMm?: number
  /** 產品特性（原表獨立欄位），即系統的「產品說明」 */
  characteristics?: string
}

/** 幅寬原文取數值：範圍取低標（58/60" → 58），單值直接取（120" → 120） */
function parseWidth(spec: string): number | undefined {
  const first = spec.match(/\d+(\.\d+)?/)
  return first ? Number(first[0]) : undefined
}

const num = (v: string | undefined) => (v && v.trim() ? Number(v.trim()) : undefined)
const str = (v: string | undefined) => (v && v.trim() ? v.trim() : undefined)

